    private void jAmbilSemuaDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jAmbilSemuaDataActionPerformed
        // TODO add your handling code here:
        dlmId.clear();
        dlmNama.clear();
      MysqlMahasiswaService service = new MysqlMahasiswaService();
      List<Mahasiswa> list = service.getAll();
       for (Mahasiswa m : list) {
        addItem(m.getId(), m.getNama());
    }

        
    }//GEN-LAST:event_jAmbilSemuaDataActionPerformed

    private void jTambahkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTambahkanActionPerformed
        // TODO add your handling code here:
        String nama = jTextFieldNama.getText().trim();
        MysqlMahasiswaService service = new MysqlMahasiswaService();
        Mahasiswa mhs = service.makeMhsObject();
        mhs.setNama(nama);
        service.add(mhs);
        List<Mahasiswa> list = service.getAll();
        addItem(list.get(list.size()-1).getId(), nama);
   
    
        
        jTextFieldNama.setText("");

    }//GEN-LAST:event_jTambahkanActionPerformed

