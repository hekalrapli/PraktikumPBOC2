    private void jEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jEditActionPerformed
        // TODO add your handling code here:
        int index = jListId.getSelectedIndex();
        String namaBaru = jTextFieldNamaEdit.getText().trim();
        int id = Integer.parseInt(dlmId.getElementAt(index));
        MysqlMahasiswaService service = new MysqlMahasiswaService();
        Mahasiswa mhs = service.makeMhsObject();
        mhs.setId(id);
        mhs.setNama(namaBaru);
        service.update(mhs);
        dlmNama.setElementAt(namaBaru, index);
          jTextFieldIdEdit.setText("");
            jTextFieldNamaEdit.setText("");
                
              
            jTextFieldIdHapus.setText("");
            jTextFieldNamaHapus.setText("");
        
        
    }//GEN-LAST:event_jEditActionPerformed

    private void jResetIndexActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jResetIndexActionPerformed
        // TODO add your handling code here:
        MysqlMahasiswaService service = new MysqlMahasiswaService();
       
        if(service.isEmpty()) {
            service.indexReset();
            jLabelReset.setText("Index direset ke 1");
        }else {
            JOptionPane.showMessageDialog(this,
            "Tabel tidak kosong!\nHapus semua data dulu.",
            "Peringatan", JOptionPane.WARNING_MESSAGE);
            
        }
           
    }//GEN-LAST:event_jResetIndexActionPerformed

    private void jHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jHapusActionPerformed
        // TODO add your handling code here:
        int index = jListId.getSelectedIndex();
        int id = Integer.parseInt(dlmId.getElementAt(index));
        MysqlMahasiswaService service = new MysqlMahasiswaService();
         service.delete(id);
         dlmNama.removeElementAt(index);
         dlmId.removeElementAt(index);
         
                jTextFieldIdEdit.setText("");
                jTextFieldNamaEdit.setText("");
                
                
                jTextFieldIdHapus.setText("");
                jTextFieldNamaHapus.setText("");
        
    }//GEN-LAST:event_jHapusActionPerformed

